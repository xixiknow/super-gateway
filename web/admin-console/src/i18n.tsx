export type MessageKey = keyof typeof messages;

function interpolate(template: string, variables?: Variables): string {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

export function translate(locale: Locale, key: MessageKey, variables?: Variables): string {
  return interpolate(messages[key][locale === "zh-CN" ? 0 : 1], variables);
}

export function resolveInitialLocale(saved?: string | null, languages?: readonly string[]): Locale {
  if (saved === "zh-CN" || saved === "en-US") return saved;
  const preferred = languages?.find(Boolean)?.toLowerCase() ?? "";
  return preferred.startsWith("zh") ? "zh-CN" : "en-US";
}

const storageKey = "super-gateway.admin.locale";

function storedLocale(): string | null {
  try {
    return window.localStorage.getItem(storageKey);
  } catch {
    return null;
  }
}

interface I18nValue {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(key: MessageKey, variables?: Variables): string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(() => initialLocale ?? resolveInitialLocale(storedLocale(), navigator.languages));
  const value = useMemo<I18nValue>(() => ({ locale, setLocale, t: (key, variables) => translate(locale, key, variables) }), [locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = translate(locale, "app.title");
    try {
      window.localStorage.setItem(storageKey, locale);
    } catch {
      // Language still changes for the current session when storage is unavailable.
    }
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is missing");
  return value;
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className={`language-switch ${compact ? "compact" : ""}`} role="group" aria-label={t("language.switch")}>
      <span className="lang-globe" aria-hidden="true"><svg className="icon"><use href="#i-globe" /></svg></span>
      <button type="button" className={locale === "zh-CN" ? "active" : ""} aria-pressed={locale === "zh-CN"} onClick={() => setLocale("zh-CN")}>{t("language.chinese")}</button>
      <button type="button" className={locale === "en-US" ? "active" : ""} aria-pressed={locale === "en-US"} onClick={() => setLocale("en-US")}>{t("language.english")}</button>
    </div>
  );
}
